#!/usr/bin/env python3
"""Generate the requirement-to-test traceability matrix from @pytest.mark.req("SRS-...") markers.

Usage: python3 scripts/trace_matrix.py [--junit results.xml] > docs/validation/trace-matrix.md
With --junit (pytest --junitxml=results.xml), each test's pass/fail result is included.
"""
import ast
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRS = ROOT / "docs" / "validation" / "srs.md"


def requirements() -> dict[str, str]:
    reqs = {}
    for line in SRS.read_text().splitlines():
        m = re.match(r"\|\s*(SRS-[A-Z]+-\d+)\s*\|\s*([^|]+)\|", line)
        if m:
            reqs[m.group(1)] = m.group(2).strip()
    return reqs


def markers() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for f in sorted((ROOT / "backend" / "tests").glob("test_*.py")):
        tree = ast.parse(f.read_text())
        for node in tree.body:
            if isinstance(node, ast.FunctionDef):
                for d in node.decorator_list:
                    if (isinstance(d, ast.Call) and getattr(d.func, "attr", "") == "req" and d.args
                            and isinstance(d.args[0], ast.Constant)):
                        out.setdefault(d.args[0].value, []).append(f"{f.name}::{node.name}")
    return out


def junit(path: str | None) -> dict[str, str]:
    if not path:
        return {}
    res = {}
    for tc in ET.parse(path).iter("testcase"):
        key = f"{tc.get('classname', '').split('.')[-1]}.py::{tc.get('name')}"
        res[key] = "FAIL" if tc.find("failure") is not None or tc.find("error") is not None else (
            "SKIP" if tc.find("skipped") is not None else "PASS")
    return res


def main() -> None:
    jpath = sys.argv[sys.argv.index("--junit") + 1] if "--junit" in sys.argv else None
    reqs, marks, results = requirements(), markers(), junit(jpath)
    print("# Traceability matrix (generated)\n")
    print("Generated by `scripts/trace_matrix.py` from test markers. Do not edit by hand.\n")
    print("| Requirement | Description | Verifying test(s) | Result |")
    print("|---|---|---|---|")
    uncovered = []
    for rid, desc in reqs.items():
        tests = marks.get(rid, [])
        if not tests:
            uncovered.append(rid)
        res = ", ".join(sorted({results.get(t, "not run") for t in tests})) if tests else "NOT COVERED"
        print(f"| {rid} | {desc} | {'<br>'.join(tests) or '—'} | {res} |")
    orphans = sorted(set(marks) - set(reqs))
    print(f"\nRequirements: {len(reqs)} · covered by automated tests: {len(reqs) - len(uncovered)}")
    if uncovered:
        print(f"\nNot covered by automated tests (verify manually in OQ): {', '.join(uncovered)}")
    if orphans:
        print(f"\nTest markers referencing unknown requirements: {', '.join(orphans)}")


if __name__ == "__main__":
    main()
